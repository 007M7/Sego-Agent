fn interactive_command_guard(command: &str) -> Option<BashCommandOutput> {
    if !runtime::bash_command_classifier::is_interactive_command(command) {
        return None;
    }

    let stderr = format!(
        "Sego blocked this interactive command to prevent the process from hanging. {command}"
    );

    Some(BashCommandOutput {
        stdout: String::new(),
        stderr: stderr.clone(),
        raw_output_path: None,
        interrupted: false,
        is_image: None,
        background_task_id: None,
        backgrounded_by_user: None,
        assistant_auto_backgrounded: None,
        dangerously_disable_sandbox: None,
        return_code_interpretation: Some("preflight_blocked:interactive_command".to_string()),
        no_output_expected: Some(true),
        structured_content: Some(vec![serde_json::to_value(
            LaneEvent::new(LaneEventName::Blocked, LaneEventStatus::Blocked, iso8601_now())
                .with_failure_class(LaneFailureClass::ToolRuntime)
                .with_detail(stderr)
                .with_data(json!({
                    "blockedCommand": command,
                    "reason": "interactive_command"
                })),
        )
        .expect("lane event should serialize")]),
        persisted_output_path: None,
        persisted_output_size: None,
        sandbox_status: None,
    })
}
fn bash_file_authoring_guard(command: &str) -> Option<BashCommandOutput> {
    if !looks_like_shell_file_authoring_misuse(command) {
        return None;
    }

    let stderr = concat!(
        "Sego blocked this shell file-writing pattern because this build does not support creating ",
        "text files through shell commands. To create Markdown, JSON, or source files, use an ",
        "external editor or a supported export command like /export or sego review."
    )
    .to_string();

    Some(BashCommandOutput {
        stdout: String::new(),
        stderr: stderr.clone(),
        raw_output_path: None,
        interrupted: false,
        is_image: None,
        background_task_id: None,
        backgrounded_by_user: None,
        assistant_auto_backgrounded: None,
        dangerously_disable_sandbox: None,
        return_code_interpretation: Some(
            "preflight_blocked:file_authoring_tool_misuse".to_string(),
        ),
        no_output_expected: Some(true),
        structured_content: Some(vec![serde_json::to_value(
            LaneEvent::new(LaneEventName::Blocked, LaneEventStatus::Blocked, iso8601_now())
                .with_failure_class(LaneFailureClass::ToolRuntime)
                .with_detail(stderr)
                .with_data(json!({
                    "blockedCommand": command,
                    "recommendedAction": "external_editor_or_export",
                    "reason": "file_authoring_tool_misuse"
                })),
        )
        .expect("lane event should serialize")]),
        persisted_output_path: None,
        persisted_output_size: None,
        sandbox_status: None,
    })
}

fn looks_like_shell_file_authoring_misuse(command: &str) -> bool {
    let lower = format!(" {} ", command.to_ascii_lowercase());
    let targets_text_file = [
        ".md",
        ".markdown",
        ".txt",
        ".json",
        ".rs",
        ".py",
        ".js",
        ".ts",
        ".tsx",
        ".jsx",
        ".toml",
        ".yaml",
        ".yml",
    ]
    .iter()
    .any(|extension| lower.contains(extension));
    if !targets_text_file {
        return false;
    }

    let shell_write = lower.contains(" > ")
        || lower.contains(">>")
        || lower.contains(" set-content ")
        || lower.contains(" out-file ")
        || lower.contains("writefile")
        || lower.contains("writefilesync")
        || lower.contains("python -c")
        || lower.contains("node -e");
    if !shell_write {
        return false;
    }

    let echo_count = lower.matches(" echo ").count()
        + lower.matches("&echo ").count()
        + lower.matches(";echo ").count();
    echo_count >= 2
        || lower.contains(" set-content ")
        || lower.contains(" out-file ")
        || lower.contains("writefile")
        || lower.contains("writefilesync")
        || lower.contains("python -c")
        || lower.contains("node -e")
}

fn workspace_test_branch_preflight(command: &str) -> Option<BashCommandOutput> {
    if !is_workspace_test_command(command) {
        return None;
    }

    let branch = git_stdout(&["branch", "--show-current"])?;
    let main_ref = resolve_main_ref(&branch)?;
    let freshness = check_freshness(&branch, &main_ref);
    match freshness {
        BranchFreshness::Fresh => None,
        BranchFreshness::Stale { commits_behind, missing_fixes } => Some(branch_divergence_output(
            command,
            &branch,
            &main_ref,
            commits_behind,
            None,
            &missing_fixes,
        )),
        BranchFreshness::Diverged { ahead, behind, missing_fixes } => {
            Some(branch_divergence_output(
                command,
                &branch,
                &main_ref,
                behind,
                Some(ahead),
                &missing_fixes,
            ))
        }
    }
}

fn is_workspace_test_command(command: &str) -> bool {
    let normalized = normalize_shell_command(command);
    [
        "cargo test --workspace",
        "cargo test --all",
        "cargo nextest run --workspace",
        "cargo nextest run --all",
    ]
    .iter()
    .any(|needle| normalized.contains(needle))
}

fn normalize_shell_command(command: &str) -> String {
    command.split_whitespace().collect::<Vec<_>>().join(" ").to_ascii_lowercase()
}

fn resolve_main_ref(branch: &str) -> Option<String> {
    let has_local_main = git_ref_exists("main");
    let has_remote_main = git_ref_exists("origin/main");

    if branch == "main" && has_remote_main {
        Some("origin/main".to_string())
    } else if has_local_main {
        Some("main".to_string())
    } else if has_remote_main {
        Some("origin/main".to_string())
    } else {
        None
    }
}

fn git_ref_exists(reference: &str) -> bool {
    Command::new("git")
        .args(["rev-parse", "--verify", "--quiet", reference])
        .output()
        .is_ok_and(|output| output.status.success())
}

fn git_stdout(args: &[&str]) -> Option<String> {
    let output = Command::new("git").args(args).output().ok()?;
    if !output.status.success() {
        return None;
    }
    let stdout = String::from_utf8_lossy(&output.stdout).trim().to_string();
    (!stdout.is_empty()).then_some(stdout)
}

fn branch_divergence_output(
    command: &str,
    branch: &str,
    main_ref: &str,
    commits_behind: usize,
    commits_ahead: Option<usize>,
    missing_fixes: &[String],
) -> BashCommandOutput {
    let relation = commits_ahead.map_or_else(
        || format!("is {commits_behind} commit(s) behind"),
        |ahead| format!("has diverged ({ahead} ahead, {commits_behind} behind)"),
    );
    let missing_summary = if missing_fixes.is_empty() {
        "(none surfaced)".to_string()
    } else {
        missing_fixes.join("; ")
    };
    let stderr = format!(
        "branch divergence detected before workspace tests: `{branch}` {relation} `{main_ref}`. Missing commits: {missing_summary}. Merge or rebase `{main_ref}` before re-running `{command}`."
    );

    BashCommandOutput {
        stdout: String::new(),
        stderr: stderr.clone(),
        raw_output_path: None,
        interrupted: false,
        is_image: None,
        background_task_id: None,
        backgrounded_by_user: None,
        assistant_auto_backgrounded: None,
        dangerously_disable_sandbox: None,
        return_code_interpretation: Some("preflight_blocked:branch_divergence".to_string()),
        no_output_expected: Some(false),
        structured_content: Some(vec![serde_json::to_value(
            LaneEvent::new(
                LaneEventName::BranchStaleAgainstMain,
                LaneEventStatus::Blocked,
                iso8601_now(),
            )
            .with_failure_class(LaneFailureClass::BranchDivergence)
            .with_detail(stderr.clone())
            .with_data(json!({
                "branch": branch,
                "mainRef": main_ref,
                "commitsBehind": commits_behind,
                "commitsAhead": commits_ahead,
                "missingCommits": missing_fixes,
                "blockedCommand": command,
                "recommendedAction": format!("merge or rebase {main_ref} before workspace tests")
            })),
        )
        .expect("lane event should serialize")]),
        persisted_output_path: None,
        persisted_output_size: None,
        sandbox_status: None,
    }
}

