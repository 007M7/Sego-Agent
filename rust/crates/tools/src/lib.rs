fn execute_repl(input: ReplInput) -> Result<ReplOutput, String> {
    if input.code.trim().is_empty() {
        return Err(String::from("code must not be empty"));
    }
    let runtime = resolve_repl_runtime(&input.language)?;
    let started = Instant::now();
    let mut process = Command::new(runtime.program.as_ref());
    process
        .args(runtime.args)
        .arg(&input.code)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped());

    // Own process group on Unix so a timeout can reclaim the whole tree, not
    // just the interpreter (DEV-SEC-16). No-op on Windows.
    runtime::process_tree::prepare_process_group(&mut process);

    let output = if let Some(timeout_ms) = input.timeout_ms {
        let mut child = process.spawn().map_err(|error| error.to_string())?;
        // Recovery ledger (DEV-CON-08): recorded only while a task is active.
        runtime::process_tree::record_spawn(child.id(), "repl", "repl execution");
        loop {
            if child.try_wait().map_err(|error| error.to_string())?.is_some() {
                runtime::process_tree::record_exit(child.id());
                break child.wait_with_output().map_err(|error| error.to_string())?;
            }
            if started.elapsed() >= Duration::from_millis(timeout_ms) {
                // Tree first: the interpreter may have spawned helpers that
                // would outlive the direct kill.
                let pid = child.id();
                let receipt = runtime::process_tree::kill_process_tree(pid).failure_receipt(pid);
                child.kill().map_err(|error| error.to_string())?;
                child.wait_with_output().map_err(|error| error.to_string())?;
                runtime::process_tree::record_exit(pid);
                return Err(match receipt {
                    Some(receipt) => {
                        format!("REPL execution exceeded timeout of {timeout_ms} ms; {receipt}")
                    }
                    None => format!("REPL execution exceeded timeout of {timeout_ms} ms"),
                });
            }
            std::thread::sleep(Duration::from_millis(10));
        }
    } else {
        let child = process.spawn().map_err(|error| error.to_string())?;
        let pid = child.id();
        runtime::process_tree::record_spawn(pid, "repl", "repl execution");
        let output = child.wait_with_output().map_err(|error| error.to_string())?;
        runtime::process_tree::record_exit(pid);
        output
    };

    Ok(ReplOutput {
        language: input.language,
        stdout: String::from_utf8_lossy(&output.stdout).into_owned(),
        stderr: String::from_utf8_lossy(&output.stderr).into_owned(),
        exit_code: output.status.code().unwrap_or(1),
        duration_ms: started.elapsed().as_millis(),
    })
}

struct ReplRuntime {
    program: Cow<'static, str>,
    args: &'static [&'static str],
}

fn resolve_repl_runtime(language: &str) -> Result<ReplRuntime, String> {
    match language.trim().to_ascii_lowercase().as_str() {
        "python" | "py" => Ok(ReplRuntime {
            program: std::env::var("PYTHON")
                .ok()
                .filter(|value| !value.trim().is_empty())
                .map(Cow::Owned)
                .or_else(|| {
                    #[cfg(windows)]
                    {
                        // On Windows, prefer `python` / `py` before `python3` because
                        // `python3` is often a Microsoft Store alias stub that cannot run.
                        // Also filter Store app stubs specifically for Python (not globally).
                        ["python", "py", "python3"]
                            .iter()
                            .find_map(|c| python_command_path(c))
                            .map(Cow::Owned)
                    }
                    #[cfg(not(windows))]
                    {
                        resolve_first_command(&["python3", "python"]).map(Cow::Owned)
                    }
                })
                .ok_or_else(|| String::from("python runtime not found"))?,
            args: &["-c"],
        }),
        "javascript" | "js" | "node" => Ok(ReplRuntime {
            program: resolve_first_command(&["node"])
                .map(Cow::Owned)
                .ok_or_else(|| String::from("node runtime not found"))?,
            args: &["-e"],
        }),
        "sh" | "shell" | "bash" => Ok(ReplRuntime {
            program: resolve_first_command(&["bash", "sh"])
                .map(Cow::Owned)
                .ok_or_else(|| String::from("shell runtime not found"))?,
            args: &["-lc"],
        }),
        other => Err(format!("unsupported REPL language: {other}")),
    }
}

/// Find the first command from `candidates` whose resolved full path passes
/// `command_path` (i.e. exists and is not a known-broken alias). Returns the
/// full path so `Command::new` uses an exact executable, avoiding PATH ambiguity.
fn resolve_first_command(candidates: &[&'static str]) -> Option<String> {
    candidates.iter().find_map(|c| command_path(c))
}

/// Like `command_path`, but also excludes Microsoft Store app stubs
/// (e.g. `WindowsApps\python3.exe`) that report exit code 9009.
/// Only used for Python runtime detection, not general command lookup.
#[cfg(windows)]
fn python_command_path(command: &str) -> Option<String> {
    let output = std::process::Command::new("where").arg(command).output().ok()?;
    if !output.status.success() {
        return None;
    }
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .find(|line| !line.contains("\\Microsoft\\WindowsApps\\"))
        .map(ToOwned::to_owned)
}

